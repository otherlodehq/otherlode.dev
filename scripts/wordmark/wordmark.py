"""Generates the Otherlode wordmark.

The wordmark is "otherlode" in 8-bit letters drawn pixel by pixel for it,
on a light grey band like a line a coverage report marks as never run.
"other" has strokes 2 pixels wide and "lode" strokes 1 pixel wide.

Writes src/lib/wordmark.ts, which src/components/Wordmark.astro draws. With
--ts it writes the same module to a second path too, such as the copy the
server's web UI draws. With --svg it also writes a standalone SVG in fixed
colours, and with --lockup an SVG of the badge beside the wordmark, for use
outside the site. See README.md in this folder for how to run it.
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# Each letter is 7 rows of pixels: the top two for ascenders, the bottom
# five the height of an x. '#' is a pixel.
BOLD = {
    'o': ['......', '......', '.####.', '##..##', '##..##', '##..##', '.####.'],
    't': ['.##..', '.##..', '#####', '.##..', '.##..', '.##..', '..###'],
    'h': ['##....', '##....', '#####.', '##..##', '##..##', '##..##', '##..##'],
    'e': ['......', '......', '.####.', '##..##', '######', '##....', '.#####'],
    'r': ['.....', '.....', '##.##', '####.', '##...', '##...', '##...'],
}
REGULAR = {
    'l': ['##.', '.#.', '.#.', '.#.', '.#.', '.#.', '###'],
    'o': ['.....', '.....', '.###.', '#...#', '#...#', '#...#', '.###.'],
    'd': ['....#', '....#', '.####', '#...#', '#...#', '#...#', '.####'],
    'e': ['.....', '.....', '.###.', '#...#', '#####', '#....', '.####'],
}
WORD = [('other', BOLD), ('lode', REGULAR)]

GAP = 1   # pixels between letters
PAD = 1   # pixels of band around the letters
ROWS = 7


def pixels():
    """The letters' pixels as (x, y) pairs, and the band's width and height."""
    x, out = PAD, []
    for word, letters in WORD:
        for ch in word:
            rows = letters[ch]
            for y, row in enumerate(rows):
                out += [(x + i, PAD + y) for i, v in enumerate(row) if v == '#']
            x += len(rows[0]) + GAP
    return out, x - GAP + PAD, ROWS + 2 * PAD


def path(cells):
    """SVG path data with one rectangle per horizontal run of pixels."""
    cells, out = sorted(set(cells), key=lambda c: (c[1], c[0])), ''
    i = 0
    while i < len(cells):
        x, y = cells[i]
        n = 1
        while i + n < len(cells) and cells[i + n] == (x + n, y):
            n += 1
        out += f'M{x} {y}h{n}v1h-{n}z'
        i += n
    return out


TS = """/**
 * The Otherlode wordmark's pixels, which a Wordmark component draws.
 *
 * Generated by scripts/wordmark/wordmark.py in the otherlode.dev repo.
 * Change the letters there and run it again rather than editing these
 * numbers by hand.
 */

/** The band's width and height, in pixels of the wordmark's grid. */
export const wordmarkWidth = {width};
export const wordmarkHeight = {height};

/** The letters, as one path of pixel runs. */
export const lettersPath =
  '{letters}';
"""


def wordmark_body(letters, width, height, colour, band):
    return (f'<g shape-rendering="crispEdges"><rect width="{width}" height="{height}" fill="{band}"/>'
            f'<path fill="{colour}" d="{letters}"/></g>')


def svg(letters, width, height, colour, band):
    """A standalone wordmark in fixed colours, 8 pixels to each grid pixel."""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width * 8}" height="{height * 8}" role="img" aria-label="Otherlode">
  <title>Otherlode</title>
  {wordmark_body(letters, width, height, colour, band)}
</svg>
"""


# The lockup spaces the badge and the wordmark as the site header does on a
# wide screen: the badge at one screen pixel to each of its pixels, a 10
# pixel gap and the wordmark 27 pixels high. One grid pixel of the
# wordmark is 3 screen pixels.
PX = 1 / 3


def lockup(letters, width, height, colour, band, badge_svg):
    """The badge and the wordmark side by side, in one SVG."""
    view_box = re.search(r'<svg[^>]*viewBox="([^"]+)"', badge_svg).group(1)
    inner = re.sub(r'^.*?<svg[^>]*>|</svg>\s*$', '', badge_svg, flags=re.S)
    badge_w, badge_h = (float(v) * PX for v in view_box.split()[2:])
    gap = 10 * PX
    total_w, total_h = badge_w + gap + width, max(badge_h, height)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {total_w:.3f} {total_h:.3f}" role="img" aria-label="Otherlode">
  <title>Otherlode</title>
  <svg x="0" y="{(total_h - badge_h) / 2:.3f}" width="{badge_w:.3f}" height="{badge_h:.3f}" viewBox="{view_box}" shape-rendering="crispEdges">{inner}</svg>
  <g transform="translate({badge_w + gap:.3f} {(total_h - height) / 2:.3f})">
  {wordmark_body(letters, width, height, colour, band)}
  </g>
</svg>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--ts', type=Path, help='also write the TypeScript module to this path')
    parser.add_argument('--svg', type=Path, help='also write a standalone SVG to this path')
    parser.add_argument('--lockup', type=Path, help='also write the badge and wordmark together to this path')
    parser.add_argument('--badge', type=Path, help='the badge SVG for --lockup')
    parser.add_argument('--colour', default='#24201D', help='letter colour for --svg and --lockup')
    parser.add_argument('--band', default='#DDD7CE', help='band colour for --svg and --lockup')
    args = parser.parse_args()

    cells, width, height = pixels()
    letters = path(cells)
    module = TS.format(width=width, height=height, letters=letters)
    ts_path = ROOT / 'src/lib/wordmark.ts'
    ts_path.write_text(module)
    print(f'wrote {ts_path.relative_to(ROOT)}')
    if args.ts:
        args.ts.write_text(module)
        print(f'wrote {args.ts}')
    if args.svg:
        args.svg.write_text(svg(letters, width, height, args.colour, args.band))
        print(f'wrote {args.svg}')
    if args.lockup:
        if not args.badge:
            parser.error('--lockup needs --badge')
        args.lockup.write_text(lockup(letters, width, height, args.colour, args.band, args.badge.read_text()))
        print(f'wrote {args.lockup}')


if __name__ == '__main__':
    main()
